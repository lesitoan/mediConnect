export function createDoctorRecord(input: CreateDoctorInput): Doctor {
  const newId = `doc-${Date.now()}`;
  const randomNum = Math.floor(100 + Math.random() * 900);
  const code = `DOC-${randomNum}`;

  return {
    id: newId,
    code,
    name: input.name,
    title: `${input.degree} ${input.name}`,
    degree: input.degree,
    avatarUrl: input.avatarUrl || "/images/doctors/doctor-1-4a0be7.png",
    specialtyId: "spec-custom",
    specialtyName: input.specialtyName,
    experienceYears: input.experienceYears || 1,
    weeklyAppointments: 0,
    rating: 5.0,
    reviewCount: 0,
    status: "ACTIVE",
    licenseNumber: input.licenseNumber,
    licenseIssuer: "Bộ Y Tế Việt Nam",
    licenseExpiry: "Đến hết 2030 (Còn hạn)",
    room: input.room,
    email: input.email,
    phone: input.phone,
    scheduleSummary: input.scheduleSummary || "Thứ 2, 4, 6 (Ca sáng)",
    patientLimitPerSession: input.patientLimitPerSession || 20,
  };
}

export function updateDoctorRecord(existing: Doctor, input: UpdateDoctorInput): Doctor {
  return {
    ...existing,
    name: input.name,
    degree: input.degree,
    title: `${input.degree} ${input.name}`,
    licenseNumber: input.licenseNumber,
    specialtyName: input.specialtyName,
    experienceYears: input.experienceYears,
    room: input.room,
    email: input.email,
    phone: input.phone,
    scheduleSummary: input.scheduleSummary,
    patientLimitPerSession: input.patientLimitPerSession,
    avatarUrl: input.avatarUrl || existing.avatarUrl,
    licenseIssuer: input.licenseIssuer || existing.licenseIssuer,
    licenseExpiry: input.licenseExpiry || existing.licenseExpiry,
  };
}

export function createSpecialtyRecord(input: CreateSpecialtyInput): Specialty {
  const newId = `spec-${Date.now()}`;
  return {
    id: newId,
    code: input.code.toUpperCase(),
    name: input.name,
    description: input.description,
    doctorCount: 0,
    activeRooms: input.activeRooms || 1,
    headDoctorName: input.headDoctorName || "Đang cập nhật",
    iconName: input.iconName || "Stethoscope",
  };
}
